                 INNER JOIN XTIPOPARCELA XTIPOPARC				(NOLOCK)ON XCOMPO.COD_TIPO_PARC = XTIPOPARC.COD_TIPO_PARC						AND XTIPOPARC.DSC_TIPO_PARC LIKE '%Financiamento%'
