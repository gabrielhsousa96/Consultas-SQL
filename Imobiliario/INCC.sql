                INNER JOIN XPARCELACOMPONENTE		(NOLOCK)ON XREGRACOMPONENTEVENDA.CODCOLIGADA = XPARCELACOMPONENTE.CODCOLIGADA AND XREGRACOMPONENTEVENDA.NUM_VENDA = XPARCELACOMPONENTE.NUM_VENDA AND XREGRACOMPONENTEVENDA.COD_GRUPO = XPARCELACOMPONENTE.COD_GRUPO AND XREGRACOMPONENTEVENDA.COD_COMPN = XPARCELACOMPONENTE.COD_COMPN
                CROSS APPLY 
							(SELECT XREGRACOMP.COD_GRUPO
                             FROM   XREGRACOMPONENTEVENDA XREGRACOMP	(NOLOCK)
                             INNER JOIN XCOMPONENTE XCOMP				(NOLOCK)ON XREGRACOMP.COD_COMPN = XCOMP.COD_COMPN AND XCOMP.DSC_COMPN LIKE 'Financiamento%' AND XCOMP.DSC_COMPN NOT LIKE '%INCC%'
                             WHERE  XREGRACOMP.CODCOLIGADA = XVENDA.CODCOLIGADA
                             AND XREGRACOMP.NUM_VENDA = XVENDA.NUM_VENDA
                             AND XREGRACOMP.COD_GRUPO = XPARCELACOMPONENTE.COD_GRUPO) GRUPOIN
                CROSS APPLY 
							(SELECT Max(XREGRACOMP.COD_GRUPO) COD_GRUPO
                             FROM   XREGRACOMPONENTEVENDA XREGRACOMP	(NOLOCK)
                             INNER JOIN XCOMPONENTE XCOMP				(NOLOCK)ON XREGRACOMP.COD_COMPN = XCOMP.COD_COMPN AND XCOMP.DSC_COMPN LIKE 'Financiamento%' AND XCOMP.DSC_COMPN NOT LIKE '%INCC%'
                             WHERE  XREGRACOMP.CODCOLIGADA = XVENDA.CODCOLIGADA
                             AND XREGRACOMP.NUM_VENDA = XVENDA.NUM_VENDA) GRUPONOT
							 WHERE  XVENDA.CODCOLIGADA IN (@CODCOLIGADA)
							 AND GRUPOIN.COD_GRUPO <> GRUPONOT.COD_GRUPO
							 AND XPARCELACOMPONENTE.VR_BAIXA > 0
							 GROUP  BY XVENDA.CODCOLIGADA,
							 XVENDA.NUM_VENDA)

