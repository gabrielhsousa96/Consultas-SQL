WITH DATAEFETIVA
     AS ((SELECT DISTINCT 
		CASE
			WHEN VENDADIRETA.DATAEMISSAO IS NOT NULL												THEN VENDADIRETA.DATAEMISSAO
            WHEN VENDADIRETA.DATAEMISSAO IS NULL AND VENDA.DAT_VENDA > XUNCOMPL.DTPRIMEIRADEMANDA	THEN VENDA.DAT_VENDA
            WHEN VENDADIRETA.DATAEMISSAO IS NULL AND VENDA.DAT_VENDA <= XUNCOMPL.DTPRIMEIRADEMANDA	THEN XUNCOMPL.DTPRIMEIRADEMANDA
            ELSE VENDA.DAT_VENDA 
         END DATA,
         VENDA.CODCOLIGADA,
         VENDA.NUM_VENDA

         FROM XVENDA				VENDA (NOLOCK)
         LEFT JOIN XVENDACOMPL		COMPL (NOLOCK)									ON VENDA.CODCOLIGADA = COMPL.CODCOLIGADA			AND VENDA.NUM_VENDA = COMPL.NUMVENDA
         LEFT JOIN GCOTACAO			GC (NOLOCK)										ON SIMBOLO = 'INCC'
         INNER JOIN XITEMVENDA		XITEM (NOLOCK)									ON VENDA.NUM_VENDA = XITEM.NUM_VENDA
         INNER JOIN XUNIDADE		XUN (NOLOCK)									ON XITEM.COD_PESS_EMPR = XUN.COD_PESS_EMPR			AND XITEM.NUM_UNID = XUN.NUM_UNID
         LEFT JOIN XUNIDADECOMPL	XUNCOMPL (NOLOCK)								ON XUN.COD_PESS_EMPR = XUNCOMPL.COD_PESS_EMPR		AND XUN.NUM_UNID = XUNCOMPL.NUM_UNID
         LEFT JOIN XSITUACAOVENDA	XSITUACAO (NOLOCK)								ON VENDA.COD_SIT_VENDA = XSITUACAO.COD_SIT_VENDA	AND Upper(XSITUACAO.DSC_SIT_VENDA) NOT LIKE 'DISTRATADA'
         OUTER APPLY	
				(SELECT Max(XREGRAADIT.DATA_EMISSAO) AS DATAEMISSAO		
                 FROM   XADIT									(NOLOCK)
                 INNER JOIN XADITRENEGOCIACAO					(NOLOCK)ON XADIT.CODCOLIGADA = XADITRENEGOCIACAO.CODCOLIGADA					AND XADIT.NUMVENDA = XADITRENEGOCIACAO.NUMVENDA						AND XADIT.NUMADIT = XADITRENEGOCIACAO.NUMADIT
