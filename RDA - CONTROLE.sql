INNER JOIN TPRODUTODEF as PRODUTO_DEF			(NOLOCK) ON (PRODUTO_DEF.IDPRD = PRODUTO.IDPRD AND PRODUTO_DEF.CODCOLIGADA = PRODUTO.CODCOLIGADA) 
LEFT JOIN TPRDGRUPOPRODUTO						(NOLOCK) ON (TPRDGRUPOPRODUTO.IDPRD = PRODUTO.IDPRD AND TPRDGRUPOPRODUTO.CODCOLPRD = PRODUTO.CODCOLIGADA)
LEFT JOIN TGRUPOPRODUTO							(NOLOCK) ON (TGRUPOPRODUTO.CODCOLIGADA = TPRDGRUPOPRODUTO.CODCOLPRD AND TGRUPOPRODUTO.CODGRUPO = TPRDGRUPOPRODUTO.CODGRUPO)
LEFT  JOIN FCFO 								(NOLOCK) ON (TMOV.CODCOLCFO = FCFO.CODCOLIGADA AND TMOV.CODCFO = FCFO.CODCFO)
LEFT JOIN TMOVAPROVA 							(NOLOCK) ON (TMOV.CODCOLIGADA = TMOVAPROVA.CODCOLIGADA AND TMOV.IDMOV = TMOVAPROVA.IDMOV AND TMOVAPROVA.TIPOAPROVACAO = 1)
LEFT JOIN TITMMOVRATCCU							(NOLOCK) ON (TITMMOVRATCCU.IDMOV = TMOV.IDMOV AND TITMMOVRATCCU.CODCOLIGADA = TMOV.CODCOLIGADA AND TITMMOVRATCCU.NSEQITMMOV = TITMMOV.NSEQITMMOV)
LEFT JOIN TMOVRATCCULOGFAT						(NOLOCK) ON (TMOVRATCCULOGFAT.IDMOVRATCCU = TMOVRATCCU.IDMOVRATCCU AND TMOVRATCCULOGFAT.IDMOV = TMOV.IDMOV AND TMOVRATCCULOGFAT.CODCOLIGADA = TMOV.CODCOLIGADA AND TMOVRATCCULOGFAT.IDPROCESSOFAT = (SELECT MIN(IDPROCESSOFAT) FROM TMOVRATCCULOGFAT FAT WHERE TMOVRATCCULOGFAT.IDMOV = FAT.IDMOV AND FAT.CODCOLIGADA = TMOVRATCCULOGFAT.CODCOLIGADA AND FAT.IDMOVRATCCU = TMOVRATCCULOGFAT.IDMOVRATCCU))
LEFT JOIN TITMMOVRATCCULOGFAT					(NOLOCK) ON (TITMMOVRATCCULOGFAT.NSEQITMMOV= TITMMOVRATCCU.NSEQITMMOV AND TITMMOVRATCCULOGFAT.IDMOVRATCCU = TITMMOVRATCCU.IDMOVRATCCU AND TITMMOVRATCCULOGFAT.IDMOV = TITMMOVRATCCU.IDMOV AND TITMMOVRATCCULOGFAT.CODCOLIGADA = TITMMOVRATCCU.CODCOLIGADA AND TITMMOVRATCCULOGFAT.IDPROCESSOFAT = (SELECT MIN(IDPROCESSOFAT) FROM TITMMOVRATCCULOGFAT FAT WHERE TITMMOVRATCCULOGFAT.NSEQITMMOV = FAT.NSEQITMMOV AND TITMMOVRATCCULOGFAT.IDMOV = FAT.IDMOV AND FAT.CODCOLIGADA = TITMMOVRATCCULOGFAT.CODCOLIGADA AND FAT.IDMOVRATCCU = TITMMOVRATCCULOGFAT.IDMOVRATCCU))
INNER JOIN GCCUSTO								(NOLOCK) ON (TITMMOVRATCCU.CODCCUSTO = GCCUSTO.CODCCUSTO AND TITMMOVRATCCU.CODCOLIGADA = GCCUSTO.CODCOLIGADA)
INNER JOIN TMOVCOMPL							(NOLOCK) ON (TMOV.IDMOV = TMOVCOMPL.IDMOV AND TMOV.CODCOLIGADA = TMOVCOMPL.CODCOLIGADA)

