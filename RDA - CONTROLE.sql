(SELECT COUNT (*) FROM TITMMOVRATCCU WHERE IDMOV = TMOV.IDMOV AND CODCOLIGADA = TMOV.CODCOLIGADA AND TITMMOVRATCCU.NSEQITMMOV = TITMMOV.NSEQITMMOV) > = 1

THEN 

TITMMOV.PRECOUNITARIO/*(CASE WHEN TITMMOVRATCCU.VALOR = '0' OR TITMMOVRATCCU.VALOR IS NULL THEN TITMMOVRATCCULOGFAT.VALOR ELSE TITMMOVRATCCU.VALOR END)*/

