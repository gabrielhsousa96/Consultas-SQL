LEFT JOIN MTRF 									(NOLOCK) ON (MTRF.CODCOLIGADA = TITMMOV.CODCOLIGADA AND MTRF.IDPRJ = TITMMOV.IDPRJ  AND TITMMOV.IDTRF = MTRF.IDTRF)
