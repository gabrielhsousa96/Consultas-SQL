LEFT JOIN TMOVRATCCU							(NOLOCK) ON (TMOVRATCCU.CODCOLIGADA = TMOV.CODCOLIGADA AND TMOVRATCCU.IDMOV = TMOV.IDMOV)
LEFT JOIN MPRJ 									(NOLOCK) ON (ISNULL(TMOVRATCCU.CODCOLIGADA,TITMMOV.CODCOLIGADA) = MPRJ.CODCOLIGADA AND ISNULL(TMOVRATCCU.IDPRJ,TITMMOV.IDPRJ) = MPRJ.IDPRJ )
