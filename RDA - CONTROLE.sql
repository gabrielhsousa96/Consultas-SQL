	CASE WHEN LEFT(PRODUTO.CODIGOPRD,1) = 'M' THEN 'MT' ELSE
	CASE WHEN LEFT(PRODUTO.CODIGOPRD,1) = 'S' THEN 'ST' ELSE
	CASE WHEN LEFT(PRODUTO.CODIGOPRD,1) = 'E' THEN 'EQ' ELSE
	CASE WHEN LEFT(PRODUTO.CODIGOPRD,1) = 'T' THEN 'MT' ELSE
	CASE WHEN LEFT(PRODUTO.CODIGOPRD,1) = 'A' THEN 'ST'
	END
