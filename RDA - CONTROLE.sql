WHERE	TMOVRELAC.IDMOVORIGEM = TMOV.IDMOV
AND		TMOVRELAC.CODCOLORIGEM = TMOV.CODCOLIGADA
AND		FLAN.CODTB2FLX <> '129') AS REFERENCIA_PGTO,

(SELECT TOP 1 REPLACE (REPLACE (CONVERT (VARCHAR(MAX) ,FLAN.HISTORICO),CHAR(13) + CHAR(10),' '),';',' ') 
