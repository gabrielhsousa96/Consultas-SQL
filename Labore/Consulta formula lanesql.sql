SELECT 
	(CASE WHEN PFUNC.CODSINDICATO IN ('0002', '0039') 
		AND ZMDCARTASINDICAL.TIPO = 1 
		AND GETDATE() BETWEEN ZMDCARTASINDICAL.DATAENTREGA AND ZMDCARTASINDICAL.DATAVALIDADE 
	THEN 'SIM' 
	ELSE 'NAO' 
	END) AS 'PODE',
	PFUNC.CODSINDICATO,
	ZMDCARTASINDICAL.TIPO,
	ZMDCARTASINDICAL.DATAENTREGA ,
	ZMDCARTASINDICAL.DATAVALIDADE,
	PFUNC.CODCATEGORIAESOCIAL

FROM ZMDCARTASINDICAL (NOLOCK)
INNER JOIN PFUNC (NOLOCK) ON PFUNC.CODPESSOA = ZMDCARTASINDICAL.CODPESSOA




