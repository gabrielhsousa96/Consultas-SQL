WITH ANOTACAO AS (
SELECT PFUNC.CODCOLIGADA,
PPESSOA.CODIGO AS 'CODPESSOA',
PANOTAC.DTANOTACAO AS 'DATAENTREGA',
PANOTAC.DTRESOLUCAO AS 'DATAVENCIMENTO',
PANOTAC.TIPO,
PANOTAC.TEXTO as 'OBSERVACOES',
'JOB' AS 'USUARIOC',
GETDATE() AS 'DATAC',
'JOB' AS 'USUARIOE',
GETDATE() AS 'DATAE'
FROM PPESSOA 
INNER JOIN PANOTAC	(NOLOCK) ON PPESSOA.CODIGO = PANOTAC.CODPESSOA
INNER JOIN PFUNC	(NOLOCK) ON PFUNC.CODPESSOA = PPESSOA.CODIGO

where 
PANOTAC.tipo = 8
)

