SELECT (GRUPO.VALOR_LINHA * GRUPO.QTD_PASSES) AS 'VALOR_DIARIO',
* 
FROM(

SELECT 
PFUNC.CODCOLIGADA, 
PFUNC.CODFILIAL, 
PFUNC.CHAPA, 
PFUNC.NOME, 
PPESSOA.CPF, 
