SELECT DISTINCT TPRDGRUPOPRODUTO.CODGRUPO, (TGRUPOPRODUTO.CODGRUPO + ' - ' + TGRUPOPRODUTO.DESCRICAO) AS NOME_GRUPOS
FROM TPRD (NOLOCK)
INNER JOIN TPRDGRUPOPRODUTO (NOLOCK) ON (TPRDGRUPOPRODUTO.IDPRD = TPRD.IDPRD AND TPRDGRUPOPRODUTO.CODCOLPRD = TPRD.CODCOLIGADA)
INNER JOIN TGRUPOPRODUTO	(NOLOCK) ON (TGRUPOPRODUTO.CODCOLIGADA = TPRDGRUPOPRODUTO.CODCOLPRD AND TGRUPOPRODUTO.CODGRUPO = TPRDGRUPOPRODUTO.CODGRUPO)

WHERE TPRD.INATIVO = 0
ORDER BY 1

select * from TGRUPOPRODUTO

