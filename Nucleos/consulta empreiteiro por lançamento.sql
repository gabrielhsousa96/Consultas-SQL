/* JOIN USANDO SELECT PARA TRAZER SALDO DE ADIANTAMENTOS DO CONTROLEMP */
LEFT JOIN(
			SELECT 
			DBCONTROLEMP.DBO.EMPREITEIRO.RM_CODCFO AS RM_CODCFO,
			DBCONTROLEMP.DBO.EMPREITEIRO.RM_CODCOLIGADA,
			DBCONTROLEMP.DBO.OBRA.RM_CODCOLIGADA AS COLIGADA_OBRA,
			DBCONTROLEMP.DBO.EMPREITEIRO.NOM_FANTASIA,
			DBCONTROLEMP.DBO.OBRA.RM_CODCCUSTO AS RM_CODCCUSTO,
			
			SUM(DBCONTROLEMP.DBO.MEDICAO_ITEM_EMPREENDIMENTO.VLR_MEDIDO) AS VLR_SALDOCONTROLEMP
			
			FROM DBCONTROLEMP.DBO.MEDICAO (NOLOCK)
			
			INNER JOIN DBCONTROLEMP.DBO.MEDICAO_ITEM_EMPREENDIMENTO	(NOLOCK) ON (DBCONTROLEMP.DBO.MEDICAO_ITEM_EMPREENDIMENTO.ID_MEDICAO = DBCONTROLEMP.DBO.MEDICAO.ID_MEDICAO)
			INNER JOIN DBCONTROLEMP.DBO.ITEM_EMPREENDIMENTO			(NOLOCK) ON (DBCONTROLEMP.DBO.MEDICAO_ITEM_EMPREENDIMENTO.ID_ITEM_EMPREENDIMENTO = DBCONTROLEMP.DBO.ITEM_EMPREENDIMENTO.ID_ITEM_EMPREENDIMENTO)
			INNER JOIN DBCONTROLEMP.DBO.CONTRATO					(NOLOCK) ON (DBCONTROLEMP.DBO.CONTRATO.ID_CONTRATO = DBCONTROLEMP.DBO.MEDICAO.ID_CONTRATO)
			INNER JOIN DBCONTROLEMP.DBO.OBRA						(NOLOCK) ON (DBCONTROLEMP.DBO.OBRA.ID_OBRA = DBCONTROLEMP.DBO.CONTRATO.ID_OBRA)
			INNER JOIN DBCONTROLEMP.DBO.EMPREITEIRO					(NOLOCK) ON (DBCONTROLEMP.DBO.EMPREITEIRO.ID_EMPREITEIRO = DBCONTROLEMP.DBO.CONTRATO.ID_EMPREITEIRO)
			
			WHERE	DBCONTROLEMP.DBO.ITEM_EMPREENDIMENTO.ID_GRUPO_ITEM = 67
			AND		DBCONTROLEMP.DBO.MEDICAO.EXCLUIDO <> 1
			AND		DBCONTROLEMP.DBO.MEDICAO.ID_ETAPA = 4
			/*ADICIONADO CODCFO PARA MELHORAR PERFORMACE DA CONSULTA*/AND (EMPREITEIRO.RM_CODCFO LIKE @EMPREITEIRO)
			GROUP BY
			
			DBCONTROLEMP.DBO.EMPREITEIRO.RM_CODCFO,
			DBCONTROLEMP.DBO.EMPREITEIRO.NOM_FANTASIA,
			DBCONTROLEMP.DBO.EMPREITEIRO.RM_CODCOLIGADA,
			DBCONTROLEMP.DBO.OBRA.RM_CODCCUSTO,
			DBCONTROLEMP.DBO.OBRA.RM_CODCOLIGADA
) AS SALDOCONTROLEMP ON (SALDOCONTROLEMP.COLIGADA_OBRA = @CODCOLIGADA AND SALDOCONTROLEMP.RM_CODCFO = EMPREITEIROS.CODCFO AND SALDOCONTROLEMP.RM_CODCCUSTO = EMPREITEIROS.CODCCUSTO AND SALDOCONTROLEMP.RM_CODCOLIGADA = EMPREITEIROS.CODCOLIGADA)
/* FIM DO JOIN COM SELECT 'SLADOCONTROLEMP' */

/* JOIN USANDO SELECT PARA TRAZER ADIANTAMENTOS PLANEJ. E CONTROLE MOV. 1.1.68 */
LEFT JOIN (
			SELECT 
			FCFO.CODCFO,
			FCFO.CODCOLIGADA,
			FCFO.NOMEFANTASIA,
			TMOV.CODCCUSTO, 
			SUM (TMOV.VALORLIQUIDO) AS VALORORIGINAL
			
			FROM TMOV (NOLOCK)
			
			INNER JOIN FCFO (NOLOCK) ON (TMOV.CODCFO = FCFO.CODCFO AND TMOV.CODCOLCFO = FCFO.CODCOLIGADA)
			
			WHERE CODTMV = '1.1.68'
			AND TMOV.CODCOLIGADA = @CODCOLIGADA 
			AND TMOV.CODCOLIGADA <> 0/*ADICIONADO PARA CORRIGIR ERRO DE DUPLICIDADE NOS VALORES - MICHELLE PIRES E ANNA CLARA*/
			/*AND TMOV.CODCFO = @EM_PREITEIRO*/
			AND FCFO.CODCFO = @EMPREITEIRO

			GROUP BY 
			FCFO.CODCFO,
			FCFO.CODCOLIGADA,
			FCFO.NOMEFANTASIA,
			TMOV.CODCCUSTO
) AS ADIANT_PLAN_CONT ON (ADIANT_PLAN_CONT.CODCFO = EMPREITEIROS.CODCFO AND ADIANT_PLAN_CONT.CODCCUSTO = EMPREITEIROS.CODCCUSTO AND ADIANT_PLAN_CONT.CODCOLIGADA = EMPREITEIROS.CODCOLIGADA)
/* FIM DO JOIN COM SELECT 'ADIANT_PLAN_CONT' */

/* JOIN USANDO SELECT PARA TRAZER ADIANTAMENTOS DIVERSOS OBRA MOV. 1.1.63 */
LEFT JOIN (
			SELECT 
			FCFO.CODCFO,
			FCFO.CODCOLIGADA,
			FCFO.NOMEFANTASIA,
			TMOV.CODCCUSTO, 
			SUM (TMOV.VALORBRUTOORIG) AS VALORORIGINAL
			
			FROM TMOV (NOLOCK)
			
			INNER JOIN FCFO (NOLOCK) ON (TMOV.CODCFO = FCFO.CODCFO AND TMOV.CODCOLCFO = FCFO.CODCOLIGADA)
			
			WHERE CODTMV = '1.1.63'
			AND TMOV.CODCOLIGADA = @CODCOLIGADA 
			AND TMOV.CODCOLIGADA <> 0 /*ADICIONADO PARA CORRIGIR ERRO DE DUPLICIDADE NOS VALORES - MICHELLE PIRES E ANNA CLARA*/
			/*AND TMOV.CODCFO = @EM_PREITEIRO*/
			AND (FCFO.CODCFO = @EMPREITEIRO)
			GROUP BY 
			FCFO.CODCFO,
			FCFO.CODCOLIGADA,
			FCFO.NOMEFANTASIA,
			TMOV.CODCCUSTO
) AS ADIANT_DIVER_OBRA ON (ADIANT_DIVER_OBRA.CODCFO = EMPREITEIROS.CODCFO AND ADIANT_DIVER_OBRA.CODCCUSTO = EMPREITEIROS.CODCCUSTO AND ADIANT_DIVER_OBRA.CODCOLIGADA = EMPREITEIROS.CODCOLIGADA)

/* FIM DO JOIN COM SELECT 'ADIANT_DIVER_OBRA' */
) AS GRUPO

GROUP BY 
GRUPO.CODCFO, 
GRUPO.NOMEFANTASIA, 
GRUPO.NOME,
GRUPO.CGCCFO,
GRUPO.DATACRIACAO,
GRUPO.CODCCUSTO,
GRUPO.COLIGADA