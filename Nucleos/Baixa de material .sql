    WHEN DBCONTROLEMP.RMO.REQUISICAO_MATERIAL.DESCONTAR_MEDICAO = 1 AND DBCONTROLEMP..EMPREITEIRO.NOM_EMPREITEIRO IS NOT NULL	THEN ('MATERIAL PARA DESCONTO' + ' - '  + DBCONTROLEMP..EMPREITEIRO.NOM_EMPREITEIRO) 
    WHEN DBCONTROLEMP.RMO.REQUISICAO_MATERIAL.DESCONTAR_MEDICAO = 1 AND DBCONTROLEMP..EMPREITEIRO.NOM_EMPREITEIRO IS NULL		THEN 'MATERIAL PARA DESCONTO - EMCCAMP'
	WHEN DBCONTROLEMP.RMO.REQUISICAO_MATERIAL.DESCONTAR_MEDICAO = 0 AND DBCONTROLEMP..EMPREITEIRO.NOM_EMPREITEIRO IS NOT NULL	THEN DBCONTROLEMP..EMPREITEIRO.NOM_EMPREITEIRO 
    WHEN DBCONTROLEMP.RMO.REQUISICAO_MATERIAL.DESCONTAR_MEDICAO = 0 AND DBCONTROLEMP..EMPREITEIRO.NOM_EMPREITEIRO IS NULL		THEN 'EMCCAMP'
