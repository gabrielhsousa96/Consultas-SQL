WHERE CAST(REQUISICAO.DATA_EXPORTACAO AS DATE) BETWEEN @DATAINI_D AND @DATAFIM_D
AND REQUISICAO_MATERIAL.RM_CODCOLIGADA IN (@COLIGADA)	
GROUP BY 
