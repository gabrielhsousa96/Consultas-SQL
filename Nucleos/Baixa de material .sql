INNER JOIN DBCONTROLEMP.RMO.REQUISICAO_MATERIAL	(NOLOCK) ON (DBCONTROLEMP.RMO.REQUISICAO.ID_REQUISICAO = DBCONTROLEMP.RMO.REQUISICAO_MATERIAL.ID_REQUISICAO)
